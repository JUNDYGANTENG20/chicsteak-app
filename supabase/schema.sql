-- ---------- Tabel ----------
create table public.menus (
  id text primary key,
  name text not null,
  price int not null check (price > 0),
  factor numeric not null check (factor > 0)
);

create table public.ingredients (
  id text primary key,
  name text not null,
  unit text not null,
  stock numeric not null default 0 check (stock >= 0),
  initial numeric not null default 0,
  cost int not null
);

create table public.orders (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  items jsonb not null,
  total int not null,
  method text not null check (method in ('qris','cash')),
  payment text not null check (payment in ('waiting','paid')),
  status text not null check (status in ('waiting','processing','ready','completed')),
  demo boolean not null default false
);
create index orders_created_at_idx on public.orders (created_at desc);
create index orders_status_idx on public.orders (status) where status <> 'completed';

create table public.reviews (
  id bigint generated by default as identity primary key,
  order_id bigint references public.orders(id) on delete set null,
  name text not null default 'Pelanggan' check (char_length(name) <= 30),
  rating int not null check (rating between 1 and 5),
  comment text not null default '' check (char_length(comment) <= 240),
  menu text not null default '',
  created_at timestamptz not null default now(),
  demo boolean not null default false
);
create index reviews_created_at_idx on public.reviews (created_at desc);
create index reviews_order_id_idx on public.reviews (order_id);

-- Email yang boleh masuk Dashboard owner (tidak bisa dibaca dari aplikasi)
create table public.owners (email text primary key);

alter table public.menus enable row level security;
alter table public.ingredients enable row level security;
alter table public.orders enable row level security;
alter table public.reviews enable row level security;
alter table public.owners enable row level security;

